def reference(case):
    q = lambda x: D.from_float(float(x))
    r0,r1,t0,t1=map(q,case['bounds'])
    dr,dt=r1-r0,t1-t0
    jets=list(map(q,case['jets']))
    M=((1,0,0,0),(0,0,1,0),(-3,3,-2,-1),(2,-2,1,1))
    G=[[D(0) for _ in range(4)] for _ in range(4)]
    for i in range(2):
        for j in range(2):
            k=i+2*j
            G[i][j]=jets[k]
            G[i+2][j]=jets[4+k]*dr
            G[i][j+2]=jets[8+k]*dt
            G[i+2][j+2]=jets[12+k]*dr*dt
    A=[[sum(D(M[i][a])*G[a][b]*D(M[j][b]) for a in range(4) for b in range(4))
        for j in range(4)] for i in range(4)]
    def power(x,n):
        return D(1) if n==0 else x**n
    def H(r,t,order):
        x=(r-r0)/dr;y=(t-t0)/dt
        if order==0:
            return sum(A[i][j]*power(x,i)*power(y,j) for i in range(4) for j in range(4))
        return sum(i*A[i][j]*power(x,i-1)*power(y,j) for i in range(1,4) for j in range(4))/dr
    rho1,T1,rho2,T2=map(q,case['states'])
    if (rho2,T2)<(rho1,T1): rho1,T1,rho2,T2=rho2,T2,rho1,T1
    b1,b2=1/T1,1/T2
    assert r0 <= rho1 <= r1 and r0 <= rho2 <= r1
    assert t0 <= T1 <= t1 and t0 <= T2 <= t1
    assert abs(rho2-rho1) >= D('2.22e-15')+D('1.49e-8')*max(rho1,rho2)
    assert abs(b2-b1) >= D('2.22e-15')+D('1.49e-8')*max(b1,b2)
    gradients=[]
    for prop in ('p','g'):
        def f(r,t):
            return r*r*H(r,t,1) if prop=='p' else H(r,t,0)+r*H(r,t,1)
        f11,f12,f21,f22=f(rho1,T1)*b1,f(rho1,T2)*b2,f(rho2,T1)*b1,f(rho2,T2)*b2
        gradients.extend((((f21-f11)+(f22-f12))/(2*(rho2-rho1)),
                          ((f12-f11)+(f22-f21))/(2*(b2-b1))))
    pr,pb,gr,gb=gradients
    density=pr/gr
    return density,gb-pb/density

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    text=['// Generated by helmholtz_difference_reference.py; 80-digit power basis.',
          '#pragma once','namespace HelmholtzDifferenceReference {',
          'struct Case { double bounds[4]; double states[4]; double jets[16]; double expected[2]; };',
          'inline constexpr Case cases[] = {']
    with localcontext() as ctx:
        ctx.prec=80
        for case in CASES:
            fields=[case['bounds'],case['states'],case['jets'],reference(case)]
            text.append('  {')
            for values in fields:
                text.append('    {'+', '.join(repr(float(v)) for v in values)+'},')
            text.append('  },')
    text.extend(['};','}'])
    args.output.write_text('\n'.join(text)+'\n')
if __name__=='__main__': main()
