#!/usr/bin/env python3
"""Generate independent80-digit mean references from binary64 corner/state inputs."""
import argparse
from decimal import Decimal, localcontext
import json
from math import factorial
from pathlib import Path


def reference(case):
    """Physical power basis A=M G M^T; no production interpolation calls."""
    number = lambda value: Decimal.from_float(float(value))
    r0, r1, t0, t1 = map(number, case['bounds'])
    dr, dt = r1-r0, t1-t0
    jets = list(map(number, case['jets']))
    matrix = ((1, 0, 0, 0), (0, 0, 1, 0), (-3, 3, -2, -1), (2, -2, 1, 1))
    corners = [[Decimal(0) for _ in range(4)] for _ in range(4)]
    for i in range(2):
        for j in range(2):
            index = i + 2*j
            corners[i][j] = jets[index]
            corners[i+2][j] = jets[4+index]*dr
            corners[i][j+2] = jets[8+index]*dt
            corners[i+2][j+2] = jets[12+index]*dr*dt
    coefficients = [
        [sum(Decimal(matrix[i][a])*corners[a][b]*Decimal(matrix[j][b])
             for a in range(4) for b in range(4)) for j in range(4)]
        for i in range(4)]

    def power(value, exponent):
        return Decimal(1) if exponent == 0 else value**exponent

    def h(rho, temperature, nr=0, nt=0):
        x, y = (rho-r0)/dr, (temperature-t0)/dt
        return sum(coefficients[i][j]*Decimal(factorial(i)//factorial(i-nr))
                   *Decimal(factorial(j)//factorial(j-nt))*power(x, i-nr)*power(y, j-nt)
                   for i in range(nr, 4) for j in range(nt, 4))/(dr**nr*dt**nt)

    rho1, temp1, rho2, temp2 = map(number, case['states'])
    if not (r0 <= rho1 <= r1 and r0 <= rho2 <= r1 and
            t0 <= temp1 <= t1 and t0 <= temp2 <= t1):
        raise ValueError('Reference states must lie inside the supplied cell')
    beta1, beta2 = 1/temp1, 1/temp2
    rho_difference = abs(rho2-rho1) >= Decimal('2.22e-15') + Decimal('1.49e-8')*max(rho1, rho2)
    beta_difference = abs(beta2-beta1) >= Decimal('2.22e-15') + Decimal('1.49e-8')*max(beta1, beta2)
    gradients = []
    for property in ('pressure', 'gibbs'):
        def value(rho, temperature):
            if property == 'pressure':
                return rho*rho*h(rho, temperature, 1, 0)
            return h(rho, temperature) + rho*h(rho, temperature, 1, 0)

        def density_derivative(rho, temperature):
            if property == 'pressure':
                return 2*rho*h(rho, temperature, 1, 0) + rho*rho*h(rho, temperature, 2, 0)
            return 2*h(rho, temperature, 1, 0) + rho*h(rho, temperature, 2, 0)

        def temperature_derivative(rho, temperature):
            if property == 'pressure':
                return rho*rho*h(rho, temperature, 1, 1)
            return h(rho, temperature, 0, 1) + rho*h(rho, temperature, 1, 1)

        f11, f12 = value(rho1, temp1), value(rho1, temp2)
        f21, f22 = value(rho2, temp1), value(rho2, temp2)
        if rho_difference:
            gradient_rho = ((f21-f11)*beta1 + (f22-f12)*beta2)/(2*(rho2-rho1))
        else:
            gradient_rho = (density_derivative(rho1, temp1)*beta1
                            + density_derivative(rho2, temp2)*beta2)/2
        if beta_difference:
            gradient_beta = ((f12*beta2-f11*beta1) + (f22*beta2-f21*beta1))/(2*(beta2-beta1))
        else:
            gradient_beta = (f11-temp1*temperature_derivative(rho1, temp1)
                             + f22-temp2*temperature_derivative(rho2, temp2))/2
        gradients.extend((gradient_rho, gradient_beta))
    pr, pb, gr, gb = gradients
    density = pr/gr
    return density, gb-pb/density


def generate(cases):
    lines = ['// Generated by helmholtz_channel_difference_reference.py;80-digit power basis.',
             '#pragma once', 'namespace ChannelMeanReference {',
             'struct Case { double bounds[4], states[4], jets[16], expected[2]; };',
             'inline constexpr Case cases[] = {']
    with localcontext() as context:
        context.prec = 80
        for case in cases:
            lines.append('  {')
            for values in (case['bounds'], case['states'], case['jets'], reference(case)):
                lines.append('    {' + ', '.join(repr(float(value)) for value in values) + '},')
            lines.append('  },')
    lines.extend(('};', '}'))
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    inputs = Path(__file__).with_name('helmholtz_channel_difference_inputs.json')
    args.output.write_text(generate(json.loads(inputs.read_text())['cases']))


if __name__ == '__main__':
    main()
